export function searchCoins(query) {
  if (!query || query.trim() === '') return COIN_DATABASE;
  const q = query.toLowerCase();
  return COIN_DATABASE.filter(
    (coin) =>
      coin.name.toLowerCase().includes(q) ||
      coin.country.toLowerCase().includes(q) ||
      coin.year.toString().includes(q) ||
      coin.denomination.toLowerCase().includes(q) ||
      coin.tags.some((tag) => tag.toLowerCase().includes(q))
  );
}

export function getCoinById(id) {
  return COIN_DATABASE.find((coin) => coin.id === id) || null;
}

export function filterCoins({ country, rarity, yearFrom, yearTo, tags } = {}) {
  return COIN_DATABASE.filter((coin) => {
    if (country && coin.country !== country) return false;
    if (rarity && coin.rarity !== rarity) return false;
    if (yearFrom && coin.year < yearFrom) return false;
    if (yearTo && coin.year > yearTo) return false;
    if (tags && tags.length > 0 && !tags.some((t) => coin.tags.includes(t))) return false;
    return true;
  });
}
